// Run: node scripts/gen-shoe-catalogue.mjs
// Source of truth: the appendix table in docs/superpowers/specs/2026-11-23-shoes-design.md
// (columns: Brand | 750 | 700 | 650 | 550 | 400). Re-run after editing the table, then run the SQL again.
import { readFileSync, writeFileSync } from 'node:fs'

const spec = readFileSync(new URL('../docs/superpowers/specs/2026-11-23-shoes-design.md', import.meta.url), 'utf8')
const appendix = spec.slice(spec.indexOf('## Appendix'))
const KM = [750, 700, 650, 550, 400]
const q = s => `'${s.replace(/'/g, "''")}'`

const brands = []
for (const line of appendix.split('\n')) {
  if (!line.startsWith('| ') || line.startsWith('| Brand') || line.startsWith('|---')) continue
  const cells = line.split('|').slice(1, -1).map(c => c.trim())
  const [brand, ...cols] = cells
  const models = cols.flatMap((c, i) => c.split(',').map(m => m.trim()).filter(Boolean).map(m => [m, KM[i]]))
  brands.push({ brand, models })
}
if (brands.length < 20) throw new Error(`only ${brands.length} brands parsed — table format changed?`)

let sql = `-- GENERATED by scripts/gen-shoe-catalogue.mjs from the RA-8 spec appendix. Do not edit by hand.
-- Run in the Supabase SQL Editor after 2026-11-24-shoes.sql. Safe to run again (updates km, adds new rows).

insert into public.shoe_brands (name, sort) values
${brands.map((b, i) => `  (${q(b.brand)}, ${i + 1})`).join(',\n')}
on conflict (name) do update set sort = excluded.sort;

insert into public.shoe_models (brand_id, name, recommended_km)
select b.id, m.name, m.km from (values
${brands.flatMap(b => b.models.map(([m, km]) => `  (${q(b.brand)}, ${q(m)}, ${km})`)).join(',\n')}
) as m(brand, name, km)
join public.shoe_brands b on b.name = m.brand
on conflict (brand_id, name) do update set recommended_km = excluded.recommended_km;
`
writeFileSync(new URL('../supabase/migrations/2026-11-24-shoe-catalogue.sql', import.meta.url), sql)
console.log(`${brands.length} brands, ${brands.reduce((n, b) => n + b.models.length, 0)} models`)
